const dictionaries: Record<Lang, Record<I18nKey, string>> = { zh, en };

export type TranslateVars = Record<string, string | number>;

export function translate(lang: Lang, key: I18nKey, vars?: TranslateVars): string {
  const template = dictionaries[lang][key] ?? dictionaries.zh[key] ?? key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : match,
  );
}

export type Translate = (key: I18nKey, vars?: TranslateVars) => string;

export interface I18nContextValue {
  lang: Lang;
  t: Translate;
  setLang: (lang: Lang) => void;
}

const fallbackContext: I18nContextValue = {
  lang: 'zh',
  t: (key, vars) => translate('zh', key, vars),
  setLang: () => undefined,
};

export const I18nContext = createContext<I18nContextValue>(fallbackContext);

export function useI18n(): I18nContextValue {
  return useContext(I18nContext);
}

export function resolveLang(hostLocale: string | undefined, stored: string | null): Lang {
  if (stored === 'zh' || stored === 'en') return stored;
  return hostLocale === 'en' || hostLocale === 'zh' ? hostLocale : 'zh';
}

export function readStoredLang(): string | null {
  try {
    return localStorage.getItem(LANG_STORAGE_KEY);
  } catch {
    return null;
  }
}

export function storeLang(lang: Lang): void {
  try {
    localStorage.setItem(LANG_STORAGE_KEY, lang);
  } catch {
    /* 私密模式忽略 */
  }
}

/** 便捷 hook：返回稳定引用，避免子组件无意义重渲染。 */
export function useTranslate(lang: Lang): I18nContextValue {
  const setLang = useCallback((next: Lang) => storeLang(next), []);
  return useMemo(
    () => ({ lang, t: (key: I18nKey, vars?: TranslateVars) => translate(lang, key, vars), setLang }),
    [lang, setLang],
  );
}

export function I18nProvider({ value, children }: { value: I18nContextValue; children: ReactNode }): JSX.Element {
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}
